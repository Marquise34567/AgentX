/*
 * Template Bank — compositional post generation system.
 *
 * Instead of hardcoded full-post templates, we combine:
 *   HOOK × BODY × CLOSER
 *
 * Each context type has its own component banks.
 * 50 hooks × 50 bodies × 50 closers = 125,000 unique posts per context.
 * 8+ context types = 1,000,000+ unique combinations.
 *
 * A seed system ensures the same topic never produces the same post twice:
 * each generation call uses a random seed that shuffles component selection.
 *
 * No GPU. No LLM API. Pure deterministic combinatorial generation.
 */

