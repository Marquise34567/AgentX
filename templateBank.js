// ---------------------------------------------------------------------------
// Seeded random — ensures same topic never produces same posts
// ---------------------------------------------------------------------------

function seededRandom(seed) {
  let s = seed;
  return function() {
    s = (s * 9301 + 49297) % 233280;
    return s / 233280;
  };
}

function pickWithRand(arr, rand) {
  return arr[Math.floor(rand() * arr.length)];
}

// ---------------------------------------------------------------------------
// Generate posts from a topic using the compositional system
// ---------------------------------------------------------------------------

function generateCompositional(topic, contextType, count = 5, seed = null) {
  const ctx = CONTEXTS[contextType] || CONTEXTS.statement;
  const rand = seededRandom(seed || (Date.now() + Math.floor(Math.random() * 1000000)));

  const hooks = ctx.hooks;
  const bodies = ctx.bodies;
  const closers = ctx.closers;

  // Generate a large pool by combining hooks × bodies × closers
  // We sample randomly from the combinatorial space
  const pool = [];
  const seen = new Set();
  const targetPoolSize = Math.min(count * 10, hooks.length * bodies.length * closers.length);

  let attempts = 0;
  while (pool.length < targetPoolSize && attempts < targetPoolSize * 3) {
    attempts++;
    const hook = pickWithRand(hooks, rand)(topic);
    const body = pickWithRand(bodies, rand);
    const closer = pickWithRand(closers, rand);

    // Build the post text
    let text = hook;
    if (body) text += "\n\n" + body;
    if (closer) text += "\n\n" + closer;

    // Dedup within pool
    const key = text.toLowerCase().slice(0, 80);
    if (!seen.has(key)) {
      seen.add(key);
      pool.push({ text, type: contextType.includes("milestone") ? "founder_story" : contextType === "opinion" || contextType === "prediction" || contextType === "statement" ? "contrarian" : "contrarian" });
    }
  }

  return pool;
}

// ---------------------------------------------------------------------------
// Get list of available context types
// ---------------------------------------------------------------------------

function getContextTypes() {
  return Object.keys(CONTEXTS);
}

// ---------------------------------------------------------------------------
// Count total unique combinations possible
// ---------------------------------------------------------------------------

function countCombinations() {
  const counts = {};
  let total = 0;
  for (const [name, ctx] of Object.entries(CONTEXTS)) {
    const combos = ctx.hooks.length * ctx.bodies.length * ctx.closers.length;
    counts[name] = combos;
    total += combos;
  }
  return { perContext: counts, total };
}

